import pandas as pd
import matplotlib.pyplot as plt
df=pd.read_csv("data/students.csv")
print(df)
print(df.shape)
print(df.size)
print(df.info())
print(df.describe())
max_maths=df["Maths"].max()
print(max_maths)
top_student=df.loc[df["Maths"].idxmax()]
print(top_student)
df["Total"]=df[["Maths","English","Science"]].sum(axis=1)
df["Average"]=df[["Maths","English","Science"]].mean(axis=1)
print(df)
print(df[df["Average"]<60])
dept_avg=df.groupby("Department")["Total"].mean()
print("Department wise total marks: ")
print(dept_avg)
print("Best performing depatment : ")
print(dept_avg.idxmax())
print("overall class average :", df["Average"].mean(axis=0))
x=df.loc[df["Average"].idxmax()]
print(x)
dept_maths=df.groupby("Department")["Maths"].mean()
plt.bar(dept_maths.index,dept_maths.values,color="yellow",label="depatmental maths marks")
plt.xlabel("depatments")
plt.ylabel("maths marks")
plt.title("maths marks comparison between departments")
plt.legend()
plt.tight_layout()
plt.savefig("charts/department_maths.png",dpi=300)
plt.show()
plt.hist(df["Maths"],bins=4,color="orange",edgecolor="black",label="maths marks distribution")
plt.legend()
plt.xlabel("distribution in maths marks")
plt.ylabel("number of students")
plt.title('distribution in maths marks')
plt.savefig("charts/maths_distribution.png",dpi=300)
plt.show()
plt.scatter(df["Maths"],df["Science"],marker="o", label="maths vs science marks")
plt.xlabel("maths marks")
plt.ylabel("science marks")
plt.title("marks comparison")
plt.legend()
plt.savefig("charts/maths_vs_science.png",dpi=300,bbox_inches="tight")
plt.show()
print("missing values:")
print(df.isnull().sum())
print("duplicate values:")
print(df.duplicated().sum())
low_performers=df[df["Average"]<60]
print("Number of low performing students:",len(low_performers))
dept_avg=df.groupby("Department")["Average"].mean()
print("department-wise average marks:")
print(dept_avg)
top_student=df.loc[df["Average"].idxmax()]
print("Top performing student:")
print(top_student[["Name","Department",'Average']])
print("maths average :" , df["Maths"].mean())
print("science average :" , df["Science"].mean())
print("english average :" , df["English"].mean())